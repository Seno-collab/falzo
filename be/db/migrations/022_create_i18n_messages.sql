CREATE TABLE IF NOT EXISTS i18n_messages (
    id BIGSERIAL PRIMARY KEY,
    message_key TEXT NOT NULL,
    locale TEXT NOT NULL,
    value TEXT NOT NULL,
    created_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    updated_at TIMESTAMPTZ NOT NULL DEFAULT NOW(),
    CONSTRAINT chk_i18n_messages_locale CHECK (locale IN ('en', 'vi')),
    CONSTRAINT uq_i18n_messages_key_locale UNIQUE (message_key, locale)
);

CREATE INDEX IF NOT EXISTS idx_i18n_messages_locale
    ON i18n_messages (locale);

CREATE OR REPLACE FUNCTION set_i18n_messages_updated_at()
RETURNS TRIGGER AS $$
BEGIN
    NEW.updated_at = NOW();
    RETURN NEW;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_i18n_messages_updated_at ON i18n_messages;
CREATE TRIGGER trg_i18n_messages_updated_at
BEFORE UPDATE ON i18n_messages
FOR EACH ROW
EXECUTE FUNCTION set_i18n_messages_updated_at();

CREATE OR REPLACE FUNCTION notify_i18n_messages_changed()
RETURNS TRIGGER AS $$
BEGIN
    PERFORM pg_notify('i18n_messages_changed', 'reload');
    RETURN NULL;
END;
$$ LANGUAGE plpgsql;

DROP TRIGGER IF EXISTS trg_i18n_messages_changed ON i18n_messages;
CREATE TRIGGER trg_i18n_messages_changed
AFTER INSERT OR UPDATE OR DELETE OR TRUNCATE ON i18n_messages
FOR EACH STATEMENT
EXECUTE FUNCTION notify_i18n_messages_changed();

